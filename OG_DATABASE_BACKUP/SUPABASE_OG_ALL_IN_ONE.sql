-- -----------------------------------------
-- FILE: 03_place_order.sql
-- -----------------------------------------
-- place_order: create an order, its items, and deduct stock, all or nothing.
--
-- Usage:  SELECT place_order(1, 1, '[{"product_id": 2, "quantity": 3}, {"product_id": 5, "quantity": 1}]');
-- Returns the new order_id. Any problem raises an error, and PostgreSQL then rolls back
-- everything this function did (a function always runs inside one transaction).
--
-- SECURITY DEFINER: customers have no RLS right to write orders or inventory, so the function
-- does it for them. That makes the customer check in Step 3 essential: the customer_id passed
-- in must belong to the signed-in user (auth.uid()). Grants at the bottom keep anon out.

CREATE OR REPLACE FUNCTION place_order(p_customer_id INT, p_store_id INT, p_items JSONB)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_order_id  INT;
    v_item      RECORD;
    v_price     NUMERIC(10, 2);
    v_available INT;
    v_total     NUMERIC(10, 2) := 0;
BEGIN
    -- Step 1: the item list must be a non-empty JSON array.
    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Order must contain at least one item';
    END IF;

    -- Step 2: the same product may not appear twice (order_items has one row per product).
    IF (SELECT count(*) <> count(DISTINCT e ->> 'product_id') FROM jsonb_array_elements(p_items) e) THEN
        RAISE EXCEPTION 'Each product may appear only once in an order';
    END IF;

    -- Step 3: the customer must be the signed-in user's own, and the store must exist and be active.
    IF NOT EXISTS (SELECT 1 FROM customers WHERE customer_id = p_customer_id AND auth_user_id = auth.uid()) THEN
        RAISE EXCEPTION 'Customer % is not your customer account', p_customer_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM dark_stores WHERE store_id = p_store_id AND is_active) THEN
        RAISE EXCEPTION 'Store % does not exist or is not active', p_store_id;
    END IF;

    -- Step 4: create the order header; the total is filled in after the items.
    INSERT INTO orders (customer_id, store_id)
    VALUES (p_customer_id, p_store_id)
    RETURNING order_id INTO v_order_id;

    -- Step 5: handle each item. Sorting by product_id means two simultaneous orders lock
    -- inventory rows in the same order, which avoids deadlocks.
    FOR v_item IN
        SELECT (e ->> 'product_id')::INT AS product_id,
               (e ->> 'quantity')::INT   AS quantity
        FROM jsonb_array_elements(p_items) e
        ORDER BY 1
    LOOP
        -- 5a: the item must be well-formed.
        IF v_item.product_id IS NULL OR v_item.quantity IS NULL OR v_item.quantity <= 0 THEN
            RAISE EXCEPTION 'Each item needs a product_id and a quantity greater than 0';
        END IF;

        -- 5b: the product must exist and be active; read its current price.
        SELECT price INTO v_price
        FROM products
        WHERE product_id = v_item.product_id AND is_active;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product % does not exist or is not available', v_item.product_id;
        END IF;

        -- 5c: deduct stock only if enough is left. Check and deduct happen in ONE statement,
        -- so two customers can never both take the last unit.
        UPDATE inventory
        SET current_stock = current_stock - v_item.quantity
        WHERE store_id = p_store_id
          AND product_id = v_item.product_id
          AND current_stock >= v_item.quantity;

        IF NOT FOUND THEN
            -- Nothing was updated: work out why, to give a clear message.
            SELECT current_stock INTO v_available
            FROM inventory
            WHERE store_id = p_store_id AND product_id = v_item.product_id;

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Product % is not sold at store %', v_item.product_id, p_store_id;
            END IF;
            RAISE EXCEPTION 'Not enough stock for product %: requested %, available %',
                v_item.product_id, v_item.quantity, v_available;
        END IF;

        -- 5d: save the line, keeping today's price (price_at_purchase), and add to the total.
        INSERT INTO order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (v_order_id, v_item.product_id, v_item.quantity, v_price);

        v_total := v_total + v_price * v_item.quantity;
    END LOOP;

    -- Step 6: store the final total and return the order id.
    UPDATE orders SET total_amount = v_total WHERE order_id = v_order_id;
    RETURN v_order_id;
END;
$$;

-- Only signed-in users may call it (Supabase grants new functions to anon by default).
REVOKE EXECUTE ON FUNCTION place_order(INT, INT, JSONB) FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION place_order(INT, INT, JSONB) TO authenticated;


-- -----------------------------------------
-- FILE: 04_low_stock_trigger_view.sql
-- -----------------------------------------
-- Low-stock trigger and manager view. Run after 01_schema.sql.

-- Trigger function: runs after an inventory row is updated and records a restock alert.
CREATE OR REPLACE FUNCTION create_restock_alert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- If an open alert already exists for this store/product, the unique index
    -- uq_open_restock_alert makes ON CONFLICT skip the insert instead of failing the order.
    INSERT INTO restock_alerts (store_id, product_id, stock_at_alert)
    VALUES (NEW.store_id, NEW.product_id, NEW.current_stock)
    ON CONFLICT (store_id, product_id) WHERE resolved_at IS NULL DO NOTHING;
    RETURN NEW;
END;
$$;

-- The trigger. The WHEN clause is the "crossing" rule:
--   OLD.current_stock > NEW.reorder_threshold   stock WAS above the threshold
--   NEW.current_stock <= NEW.reorder_threshold  stock IS NOW at or below it
-- Both must be true, so it fires once at the crossing, not on every later reduction
-- (5 -> 4 -> 3 fire nothing because the old value was already at or below the threshold).
CREATE OR REPLACE TRIGGER trg_low_stock_alert
AFTER UPDATE OF current_stock ON inventory
FOR EACH ROW
WHEN (OLD.current_stock > NEW.reorder_threshold AND NEW.current_stock <= NEW.reorder_threshold)
EXECUTE FUNCTION create_restock_alert();

-- Manager view: every product at or below its reorder threshold, with its open alert if there is one.
-- security_invoker makes the view obey the caller's RLS instead of the view owner's.
CREATE OR REPLACE VIEW v_low_stock_inventory
WITH (security_invoker = true) AS
SELECT s.store_id,
       s.store_name,
       p.product_id,
       p.product_name,
       c.category_name,
       i.current_stock,
       i.reorder_threshold,
       a.alert_id,
       a.created_at AS alert_created_at
FROM inventory i
JOIN dark_stores s ON s.store_id   = i.store_id       -- which store holds the stock
JOIN products p    ON p.product_id = i.product_id     -- product name
JOIN categories c  ON c.category_id = p.category_id   -- product category
LEFT JOIN restock_alerts a                            -- LEFT: keep low items that have no alert yet
       ON a.store_id = i.store_id
      AND a.product_id = i.product_id
      AND a.resolved_at IS NULL                       -- only the open alert
WHERE i.current_stock <= i.reorder_threshold;


-- -----------------------------------------
-- FILE: 05_reports.sql
-- -----------------------------------------
-- Three manager reports. Read-only; run each query on its own.

-- Report 1: low-stock items (at or below reorder threshold), most urgent first.
SELECT store_name, product_name, category_name, current_stock, reorder_threshold,
       alert_id IS NOT NULL AS has_open_alert
FROM v_low_stock_inventory
ORDER BY current_stock - reorder_threshold, product_name;

-- Report 2: top 5 best-selling products by units sold (cancelled orders ignored).
-- Revenue uses price_at_purchase, so later price changes do not distort history.
SELECT p.product_name,
       c.category_name,
       SUM(oi.quantity)                          AS units_sold,
       SUM(oi.quantity * oi.price_at_purchase)   AS revenue
FROM order_items oi
JOIN orders o     ON o.order_id    = oi.order_id
JOIN products p   ON p.product_id  = oi.product_id
JOIN categories c ON c.category_id = p.category_id
WHERE o.status <> 'cancelled'
GROUP BY p.product_id, p.product_name, c.category_name
ORDER BY units_sold DESC, revenue DESC
LIMIT 5;

-- Report 3: delivered orders per rider and average minutes from placing to delivery.
-- LEFT JOIN keeps riders who have not delivered anything yet (count 0, average empty).
SELECT r.rider_id,
       r.full_name,
       COUNT(o.order_id) AS delivered_orders,
       ROUND(AVG(EXTRACT(EPOCH FROM (o.delivered_at - o.placed_at)) / 60), 1) AS avg_delivery_minutes
FROM riders r
LEFT JOIN orders o ON o.rider_id = r.rider_id AND o.status = 'delivered'
GROUP BY r.rider_id, r.full_name
ORDER BY delivered_orders DESC, r.full_name;


-- -----------------------------------------
-- FILE: 06_auth_rls.sql
-- -----------------------------------------
-- Auth + RLS setup for manager / rider / customer. Run after 01-04, then re-run 03_place_order.sql.
--
-- Model: Supabase Auth owns emails and passwords (never stored in our tables).
--   profiles               user -> role (manager | rider | customer)
--   customers.auth_user_id user -> their customer row   (already in the schema)
--   riders.auth_user_id    user -> their rider row      (already in the schema)
-- Customers and riders never write orders or inventory directly; place_order does it for them.

-- 1. Role mapping. No INSERT/UPDATE policy exists, so users cannot give themselves a role.
CREATE TABLE profiles (
    user_id UUID PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    role    VARCHAR(20) NOT NULL CHECK (role IN ('manager', 'rider', 'customer'))
);

-- 2. Helpers. SECURITY DEFINER lets policies look up the caller's role/IDs without recursing
--    through RLS (customers' policy reads orders, orders' policy reads customers, and so on).
CREATE FUNCTION is_manager() RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (SELECT 1 FROM profiles WHERE user_id = auth.uid() AND role = 'manager');
$$;

CREATE FUNCTION my_customer_id() RETURNS INT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT customer_id FROM customers WHERE auth_user_id = auth.uid();
$$;

CREATE FUNCTION my_rider_id() RETURNS INT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT rider_id FROM riders WHERE auth_user_id = auth.uid();
$$;

-- 3. Turn RLS on (a table with RLS on and no matching policy returns no rows).
ALTER TABLE profiles       ENABLE ROW LEVEL SECURITY;
ALTER TABLE zones          ENABLE ROW LEVEL SECURITY;
ALTER TABLE dark_stores    ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories     ENABLE ROW LEVEL SECURITY;
ALTER TABLE products       ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory      ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers      ENABLE ROW LEVEL SECURITY;
ALTER TABLE riders         ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders         ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items    ENABLE ROW LEVEL SECURITY;
ALTER TABLE restock_alerts ENABLE ROW LEVEL SECURITY;

-- 4. Policies (all TO authenticated, so anonymous visitors get nothing).

-- profiles: you can read only your own row (the app uses it to pick the dashboard).
CREATE POLICY profiles_read_own ON profiles FOR SELECT TO authenticated
    USING (user_id = auth.uid());

-- Shared reference data: any signed-in user can read it.
CREATE POLICY zones_read       ON zones       FOR SELECT TO authenticated USING (true);
CREATE POLICY dark_stores_read ON dark_stores FOR SELECT TO authenticated USING (true);
CREATE POLICY categories_read  ON categories  FOR SELECT TO authenticated USING (true);
-- Customers see only active products; the manager sees all.
CREATE POLICY products_read    ON products    FOR SELECT TO authenticated
    USING (is_active OR is_manager());

-- inventory: everyone signed in can read stock (the customer page shows it); only the manager changes it.
CREATE POLICY inventory_read ON inventory FOR SELECT TO authenticated USING (true);
CREATE POLICY inventory_manager_write ON inventory FOR ALL TO authenticated
    USING (is_manager()) WITH CHECK (is_manager());

-- customers: you see your own row; the manager sees all; a rider sees only customers on their assigned orders.
CREATE POLICY customers_read ON customers FOR SELECT TO authenticated
    USING (customer_id = my_customer_id()
           OR is_manager()
           OR customer_id IN (SELECT customer_id FROM orders WHERE rider_id = my_rider_id()));

-- riders: you see your own row; the manager sees all.
CREATE POLICY riders_read ON riders FOR SELECT TO authenticated
    USING (rider_id = my_rider_id() OR is_manager());

-- orders: customers see their own, riders see the ones assigned to them, the manager sees all.
CREATE POLICY orders_read ON orders FOR SELECT TO authenticated
    USING (customer_id = my_customer_id() OR rider_id = my_rider_id() OR is_manager());

-- orders update: the manager (assigns riders) or the assigned rider (updates status).
-- WITH CHECK stops a rider handing their order to someone else. There is no INSERT or DELETE
-- policy: orders are created only by place_order.
CREATE POLICY orders_update ON orders FOR UPDATE TO authenticated
    USING      (is_manager() OR rider_id = my_rider_id())
    WITH CHECK (is_manager() OR rider_id = my_rider_id());

-- RLS limits rows, not columns, so restrict columns too: nobody can edit totals or customers.
REVOKE UPDATE ON orders FROM authenticated;
GRANT  UPDATE (rider_id, status, dispatched_at, delivered_at) ON orders TO authenticated;

-- order_items: visible exactly when the parent order is visible (the subquery obeys orders' RLS).
CREATE POLICY order_items_read ON order_items FOR SELECT TO authenticated
    USING (EXISTS (SELECT 1 FROM orders o WHERE o.order_id = order_items.order_id));

-- restock_alerts: manager only (read and resolve).
CREATE POLICY restock_alerts_manager ON restock_alerts FOR ALL TO authenticated
    USING (is_manager()) WITH CHECK (is_manager());

