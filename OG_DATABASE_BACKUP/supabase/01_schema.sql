-- Dark Store Management System: schema (Supabase PostgreSQL)
-- Run in the Supabase SQL editor on a clean database.
-- Delete rules: RESTRICT protects history/reference data, CASCADE removes pure child rows,
-- SET NULL keeps a record when an optional parent goes away.

-- 1. zones: delivery areas
CREATE TABLE zones (
    zone_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_name VARCHAR(100) NOT NULL,
    pincode   VARCHAR(10)  NOT NULL UNIQUE
);

-- 2. dark_stores: each store serves one zone
CREATE TABLE dark_stores (
    store_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name VARCHAR(100) NOT NULL,
    address    VARCHAR(255),
    zone_id    INT NOT NULL REFERENCES zones (zone_id) ON DELETE RESTRICT,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. categories: product category lookup
CREATE TABLE categories (
    category_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

-- 4. products: catalogue (stock lives in inventory, not here)
CREATE TABLE products (
    product_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(150)   NOT NULL,
    category_id  INT            NOT NULL REFERENCES categories (category_id) ON DELETE RESTRICT,
    price        NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    is_active    BOOLEAN        NOT NULL DEFAULT TRUE
);

-- 5. inventory: stock per store AND product -> composite primary key
CREATE TABLE inventory (
    store_id          INT NOT NULL REFERENCES dark_stores (store_id) ON DELETE CASCADE,
    product_id        INT NOT NULL REFERENCES products (product_id)  ON DELETE RESTRICT,
    current_stock     INT NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
    reorder_threshold INT NOT NULL DEFAULT 5 CHECK (reorder_threshold >= 0),
    PRIMARY KEY (store_id, product_id)
);

-- 6. customers: profile linked to Supabase Auth (no password stored here)
CREATE TABLE customers (
    customer_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE REFERENCES auth.users (id) ON DELETE SET NULL,
    full_name    VARCHAR(100) NOT NULL,
    phone        VARCHAR(20),
    address      VARCHAR(255),
    zone_id      INT NOT NULL REFERENCES zones (zone_id) ON DELETE RESTRICT
);

-- 7. riders: profile linked to Supabase Auth, works for one store
CREATE TABLE riders (
    rider_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE REFERENCES auth.users (id) ON DELETE SET NULL,
    full_name    VARCHAR(100) NOT NULL,
    phone        VARCHAR(20),
    store_id     INT NOT NULL REFERENCES dark_stores (store_id) ON DELETE RESTRICT,
    status       VARCHAR(20) NOT NULL DEFAULT 'available'
                 CHECK (status IN ('available', 'busy', 'offline'))
);

-- 8. orders: rider is optional until assigned
CREATE TABLE orders (
    order_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INT NOT NULL REFERENCES customers (customer_id) ON DELETE RESTRICT,
    store_id      INT NOT NULL REFERENCES dark_stores (store_id)  ON DELETE RESTRICT,
    rider_id      INT REFERENCES riders (rider_id) ON DELETE SET NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'placed'
                  CHECK (status IN ('placed', 'packed', 'out_for_delivery', 'delivered', 'cancelled')),
    total_amount  NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    placed_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    dispatched_at TIMESTAMPTZ,
    delivered_at  TIMESTAMPTZ,
    CHECK (dispatched_at IS NULL OR dispatched_at >= placed_at),
    CHECK (delivered_at  IS NULL OR delivered_at  >= placed_at)
);

-- 9. order_items: one row per product in an order -> composite primary key
CREATE TABLE order_items (
    order_id          INT NOT NULL REFERENCES orders (order_id)     ON DELETE CASCADE,
    product_id        INT NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
    quantity          INT NOT NULL CHECK (quantity > 0),
    price_at_purchase NUMERIC(10, 2) NOT NULL CHECK (price_at_purchase > 0),
    PRIMARY KEY (order_id, product_id)
);

-- 10. restock_alerts: snapshot of stock when it hit the threshold
CREATE TABLE restock_alerts (
    alert_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id       INT NOT NULL,
    product_id     INT NOT NULL,
    stock_at_alert INT NOT NULL CHECK (stock_at_alert >= 0),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at    TIMESTAMPTZ,   -- NULL = still open
    CHECK (resolved_at IS NULL OR resolved_at >= created_at),
    -- composite FK: an alert must refer to a real (store, product) inventory row
    FOREIGN KEY (store_id, product_id) REFERENCES inventory (store_id, product_id) ON DELETE CASCADE
);

-- Indexes (PKs and UNIQUE columns are already indexed; these cover other joins/filters)
CREATE INDEX idx_products_category   ON products (category_id);
CREATE INDEX idx_inventory_product   ON inventory (product_id);
CREATE INDEX idx_orders_customer     ON orders (customer_id);
CREATE INDEX idx_orders_rider        ON orders (rider_id);
CREATE INDEX idx_orders_status       ON orders (status);
CREATE INDEX idx_order_items_product ON order_items (product_id);
-- At most one open alert per store/product (supports the low-stock trigger later)
CREATE UNIQUE INDEX uq_open_restock_alert ON restock_alerts (store_id, product_id) WHERE resolved_at IS NULL;
